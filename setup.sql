-- ============================================================
-- Cost Monitoring Dashboard — Setup Script
-- ============================================================
-- Run this worksheet in Snowsight as ACCOUNTADMIN (or a role
-- with IMPORTED PRIVILEGES on SNOWFLAKE database).
--
-- What it creates:
--   DATABASE   COST_DASHBOARD
--   WAREHOUSE  COST_DASHBOARD_WH  (X-Small, auto-suspend 60s)
--   PROCEDURE  COST_DASHBOARD.PUBLIC.BACKFILL()    — full 90-day load
--   PROCEDURE  COST_DASHBOARD.PUBLIC.REFRESH()     — incremental daily
--   TASK       COST_DASHBOARD.PUBLIC.REFRESH_DAILY — runs REFRESH() at 6 AM UTC
--   10 tables  populated from SNOWFLAKE.ACCOUNT_USAGE
--
-- After this finishes, deploy the app:
--   snow app deploy
-- ============================================================

USE ROLE ACCOUNTADMIN;

-- 1. Database & warehouse
CREATE DATABASE IF NOT EXISTS COST_DASHBOARD;
CREATE SCHEMA IF NOT EXISTS COST_DASHBOARD.PUBLIC;

CREATE WAREHOUSE IF NOT EXISTS COST_DASHBOARD_WH
  WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;

USE WAREHOUSE COST_DASHBOARD_WH;

-- ============================================================
-- 2a. BACKFILL — full 90-day initial load (CREATE OR REPLACE)
-- ============================================================
CREATE OR REPLACE PROCEDURE COST_DASHBOARD.PUBLIC.BACKFILL()
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS
BEGIN
  -- ── Cost Monitor tables ──────────────────────────────────

  CREATE OR REPLACE TABLE COST_DASHBOARD.PUBLIC.METERING_DAILY_HISTORY AS
  SELECT SERVICE_TYPE,
         USAGE_DATE,
         SUM(CREDITS_USED) AS CREDITS_USED
  FROM SNOWFLAKE.ACCOUNT_USAGE.METERING_DAILY_HISTORY
  WHERE USAGE_DATE >= DATEADD(day, -90, CURRENT_DATE())
  GROUP BY SERVICE_TYPE, USAGE_DATE;

  CREATE OR REPLACE TABLE COST_DASHBOARD.PUBLIC.WAREHOUSE_DAILY AS
  SELECT START_TIME::DATE AS USAGE_DATE,
         WAREHOUSE_NAME,
         SUM(CREDITS_USED) AS CREDITS
  FROM SNOWFLAKE.ACCOUNT_USAGE.WAREHOUSE_METERING_HISTORY
  WHERE START_TIME >= DATEADD(day, -90, CURRENT_DATE())
  GROUP BY USAGE_DATE, WAREHOUSE_NAME;

  CREATE OR REPLACE TABLE COST_DASHBOARD.PUBLIC.USER_DAILY AS
  SELECT START_TIME::DATE AS USAGE_DATE,
         USER_NAME,
         SUM(CREDITS_USED_CLOUD_SERVICES) AS CREDITS
  FROM SNOWFLAKE.ACCOUNT_USAGE.QUERY_HISTORY
  WHERE START_TIME >= DATEADD(day, -90, CURRENT_DATE())
    AND USER_NAME IS NOT NULL
  GROUP BY USAGE_DATE, USER_NAME;

  CREATE OR REPLACE TABLE COST_DASHBOARD.PUBLIC.DATABASE_STORAGE_USAGE_HISTORY AS
  SELECT USAGE_DATE,
         DATABASE_NAME,
         AVERAGE_DATABASE_BYTES
  FROM SNOWFLAKE.ACCOUNT_USAGE.DATABASE_STORAGE_USAGE_HISTORY
  WHERE USAGE_DATE >= DATEADD(day, -90, CURRENT_DATE())
    AND AVERAGE_DATABASE_BYTES > 0;

  CREATE OR REPLACE TABLE COST_DASHBOARD.PUBLIC.COCO_USAGE AS
  SELECT USER_NAME,
         USAGE_TIME::DATE AS USAGE_DATE,
         TOKEN_CREDITS,
         TOKENS,
         TOKENS_GRANULAR::VARCHAR AS TOKENS_GRANULAR,
         CREDITS_GRANULAR::VARCHAR AS CREDITS_GRANULAR,
         INTERFACE,
         METADATA::VARCHAR AS METADATA,
         THREAD_ID
  FROM SNOWFLAKE.ACCOUNT_USAGE.SNOWFLAKE_COCO_USAGE_HISTORY
  WHERE USAGE_TIME >= DATEADD(day, -90, CURRENT_DATE());

  -- ── Recommendation tables (always full rebuild) ──────────

  CREATE OR REPLACE TABLE COST_DASHBOARD.PUBLIC.WAREHOUSE_SIZING AS
  SELECT WAREHOUSE_NAME,
         WAREHOUSE_SIZE,
         COUNT(*) AS TOTAL_QUERIES,
         ROUND(100.0 * SUM(CASE WHEN TOTAL_ELAPSED_TIME < 1000 THEN 1 ELSE 0 END) / COUNT(*), 1) AS OVERSIZED_PCT,
         ROUND(100.0 * SUM(CASE WHEN BYTES_SPILLED_TO_LOCAL_STORAGE + BYTES_SPILLED_TO_REMOTE_STORAGE > 0 THEN 1 ELSE 0 END) / COUNT(*), 1) AS SPILL_PCT,
         SUM(CASE WHEN TOTAL_ELAPSED_TIME > 60000 THEN 1 ELSE 0 END) AS HEAVY_QUERIES
  FROM SNOWFLAKE.ACCOUNT_USAGE.QUERY_HISTORY
  WHERE START_TIME >= DATEADD(day, -90, CURRENT_DATE())
    AND WAREHOUSE_NAME IS NOT NULL
    AND EXECUTION_STATUS = 'SUCCESS'
  GROUP BY WAREHOUSE_NAME, WAREHOUSE_SIZE
  HAVING COUNT(*) >= 100;

  CREATE OR REPLACE TABLE COST_DASHBOARD.PUBLIC.ADAPTIVE_SCORING AS
  WITH qh AS (
    SELECT WAREHOUSE_NAME,
           WAREHOUSE_SIZE,
           COUNT(*) AS TOTAL_QUERIES,
           STDDEV(TOTAL_ELAPSED_TIME) / NULLIF(AVG(TOTAL_ELAPSED_TIME), 0) AS VARIABILITY,
           ROUND(100.0 * SUM(CASE WHEN BYTES_SPILLED_TO_LOCAL_STORAGE + BYTES_SPILLED_TO_REMOTE_STORAGE > 0 THEN 1 ELSE 0 END) / COUNT(*), 1) AS SPILL_PCT,
           ROUND(100.0 * SUM(CASE WHEN TOTAL_ELAPSED_TIME < 1000 THEN 1 ELSE 0 END) / COUNT(*), 1) AS OVERSIZED_PCT,
           ROUND(100.0 * SUM(CASE WHEN TOTAL_ELAPSED_TIME > 60000 THEN 1 ELSE 0 END) / COUNT(*), 1) AS HEAVY_PCT,
           SUM(CASE WHEN QUEUED_PROVISIONING_TIME + QUEUED_OVERLOAD_TIME > 0 THEN 1 ELSE 0 END) AS QUEUED
    FROM SNOWFLAKE.ACCOUNT_USAGE.QUERY_HISTORY
    WHERE START_TIME >= DATEADD(day, -90, CURRENT_DATE())
      AND WAREHOUSE_NAME IS NOT NULL
      AND EXECUTION_STATUS = 'SUCCESS'
    GROUP BY WAREHOUSE_NAME, WAREHOUSE_SIZE
    HAVING COUNT(*) >= 100
  ),
  wm AS (
    SELECT WAREHOUSE_NAME, SUM(CREDITS_USED) AS CREDITS
    FROM SNOWFLAKE.ACCOUNT_USAGE.WAREHOUSE_METERING_HISTORY
    WHERE START_TIME >= DATEADD(day, -90, CURRENT_DATE())
    GROUP BY WAREHOUSE_NAME
  )
  SELECT qh.WAREHOUSE_NAME, qh.WAREHOUSE_SIZE, qh.TOTAL_QUERIES,
         ROUND(wm.CREDITS, 2) AS CREDITS,
         ROUND(qh.VARIABILITY, 2) AS VARIABILITY,
         qh.SPILL_PCT, qh.OVERSIZED_PCT, qh.HEAVY_PCT, qh.QUEUED,
         ROUND(LEAST(qh.VARIABILITY / 3.0 * 40, 40)
               + LEAST(qh.SPILL_PCT / 25.0 * 30, 30)
               + LEAST(qh.HEAVY_PCT / 10.0 * 20, 20)
               + LEAST(COALESCE(wm.CREDITS, 0) / 500.0 * 10, 10), 1) AS SCORE
  FROM qh LEFT JOIN wm ON qh.WAREHOUSE_NAME = wm.WAREHOUSE_NAME
  WHERE LEAST(qh.VARIABILITY / 3.0 * 40, 40)
        + LEAST(qh.SPILL_PCT / 25.0 * 30, 30)
        + LEAST(qh.HEAVY_PCT / 10.0 * 20, 20)
        + LEAST(COALESCE(wm.CREDITS, 0) / 500.0 * 10, 10) >= 25;

  CREATE OR REPLACE TABLE COST_DASHBOARD.PUBLIC.GEN2_SCORING AS
  WITH qh AS (
    SELECT WAREHOUSE_NAME,
           COUNT(*) AS TOTAL_QUERIES,
           ROUND(100.0 * SUM(CASE WHEN QUERY_TYPE IN ('DELETE','UPDATE','MERGE','INSERT') THEN 1 ELSE 0 END) / COUNT(*), 1) AS DML_PCT,
           ROUND(APPROX_PERCENTILE(TOTAL_ELAPSED_TIME, 0.95) / 1000.0, 1) AS P95_SEC,
           ROUND(100.0 * SUM(CASE WHEN BYTES_SPILLED_TO_LOCAL_STORAGE + BYTES_SPILLED_TO_REMOTE_STORAGE > 0 THEN 1 ELSE 0 END) / COUNT(*), 1) AS SPILL_PCT,
           ROUND(100.0 * SUM(CASE WHEN TOTAL_ELAPSED_TIME > 300000 THEN 1 ELSE 0 END) / COUNT(*), 1) AS LONG_PCT,
           SUM(CASE WHEN QUEUED_PROVISIONING_TIME + QUEUED_OVERLOAD_TIME > 0 THEN 1 ELSE 0 END) AS QUEUED
    FROM SNOWFLAKE.ACCOUNT_USAGE.QUERY_HISTORY
    WHERE START_TIME >= DATEADD(day, -90, CURRENT_DATE())
      AND WAREHOUSE_NAME IS NOT NULL
      AND EXECUTION_STATUS = 'SUCCESS'
    GROUP BY WAREHOUSE_NAME
    HAVING COUNT(*) >= 100
  ),
  wm AS (
    SELECT WAREHOUSE_NAME, SUM(CREDITS_USED) AS CREDITS
    FROM SNOWFLAKE.ACCOUNT_USAGE.WAREHOUSE_METERING_HISTORY
    WHERE START_TIME >= DATEADD(day, -90, CURRENT_DATE())
    GROUP BY WAREHOUSE_NAME
  )
  SELECT qh.WAREHOUSE_NAME, qh.TOTAL_QUERIES,
         ROUND(wm.CREDITS, 2) AS CREDITS,
         qh.DML_PCT, qh.P95_SEC, qh.SPILL_PCT, qh.LONG_PCT, qh.QUEUED,
         ROUND(LEAST(qh.DML_PCT / 20.0 * 30, 30)
               + LEAST(qh.SPILL_PCT / 25.0 * 20, 20)
               + LEAST(qh.LONG_PCT / 10.0 * 20, 20)
               + LEAST(qh.QUEUED / 1000.0 * 15, 15)
               + LEAST(COALESCE(wm.CREDITS, 0) / 500.0 * 15, 15), 1) AS SCORE
  FROM qh LEFT JOIN wm ON qh.WAREHOUSE_NAME = wm.WAREHOUSE_NAME
  WHERE LEAST(qh.DML_PCT / 20.0 * 30, 30)
        + LEAST(qh.SPILL_PCT / 25.0 * 20, 20)
        + LEAST(qh.LONG_PCT / 10.0 * 20, 20)
        + LEAST(qh.QUEUED / 1000.0 * 15, 15)
        + LEAST(COALESCE(wm.CREDITS, 0) / 500.0 * 15, 15) >= 25;

  CREATE OR REPLACE TABLE COST_DASHBOARD.PUBLIC.CLOUD_SERVICES_EXCESS AS
  SELECT WAREHOUSE_NAME,
         ROUND(SUM(CREDITS_USED_COMPUTE), 2) AS COMPUTE_CREDITS,
         ROUND(SUM(CREDITS_USED_CLOUD_SERVICES), 2) AS CS_CREDITS,
         ROUND(100.0 * SUM(CREDITS_USED_CLOUD_SERVICES) / NULLIF(SUM(CREDITS_USED_COMPUTE), 0), 1) AS CS_PCT,
         COUNT(DISTINCT START_TIME::DATE) AS ACTIVE_DAYS
  FROM SNOWFLAKE.ACCOUNT_USAGE.WAREHOUSE_METERING_HISTORY
  WHERE START_TIME >= DATEADD(day, -90, CURRENT_DATE())
  GROUP BY WAREHOUSE_NAME
  HAVING CS_PCT > 10 AND SUM(CREDITS_USED_COMPUTE) > 1;

  CREATE OR REPLACE TABLE COST_DASHBOARD.PUBLIC.CLUSTERING_WASTE AS
  SELECT DATABASE_NAME, SCHEMA_NAME, TABLE_NAME,
         ROUND(SUM(CREDITS_USED), 4) AS CLUSTERING_CREDITS,
         COUNT(*) AS EVENTS
  FROM SNOWFLAKE.ACCOUNT_USAGE.AUTOMATIC_CLUSTERING_HISTORY
  WHERE START_TIME >= DATEADD(day, -90, CURRENT_DATE())
  GROUP BY DATABASE_NAME, SCHEMA_NAME, TABLE_NAME
  HAVING CLUSTERING_CREDITS < 0.01;

  RETURN 'Backfill complete — 10 tables loaded at ' || CURRENT_TIMESTAMP()::VARCHAR;
END;

-- ============================================================
-- 2b. REFRESH — incremental daily (append new + trim old)
-- ============================================================
-- Appends the last 2 days of data (covers ACCOUNT_USAGE lag),
-- then deletes anything older than 90 days.
-- Recommendation tables are always full-rebuilt since they need
-- aggregate scores over the full 90-day window.
-- ============================================================
CREATE OR REPLACE PROCEDURE COST_DASHBOARD.PUBLIC.REFRESH()
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS
BEGIN
  LET cutoff := DATEADD(day, -90, CURRENT_DATE());
  LET lookback := DATEADD(day, -2, CURRENT_DATE());

  -- ── Cost Monitor tables: incremental ─────────────────────

  -- Metering daily: delete overlap window, insert fresh, trim tail
  DELETE FROM COST_DASHBOARD.PUBLIC.METERING_DAILY_HISTORY
  WHERE USAGE_DATE >= :lookback;

  INSERT INTO COST_DASHBOARD.PUBLIC.METERING_DAILY_HISTORY
  SELECT SERVICE_TYPE, USAGE_DATE, SUM(CREDITS_USED) AS CREDITS_USED
  FROM SNOWFLAKE.ACCOUNT_USAGE.METERING_DAILY_HISTORY
  WHERE USAGE_DATE >= :lookback
  GROUP BY SERVICE_TYPE, USAGE_DATE;

  DELETE FROM COST_DASHBOARD.PUBLIC.METERING_DAILY_HISTORY
  WHERE USAGE_DATE < :cutoff;

  -- Warehouse daily
  DELETE FROM COST_DASHBOARD.PUBLIC.WAREHOUSE_DAILY
  WHERE USAGE_DATE >= :lookback;

  INSERT INTO COST_DASHBOARD.PUBLIC.WAREHOUSE_DAILY
  SELECT START_TIME::DATE AS USAGE_DATE, WAREHOUSE_NAME, SUM(CREDITS_USED) AS CREDITS
  FROM SNOWFLAKE.ACCOUNT_USAGE.WAREHOUSE_METERING_HISTORY
  WHERE START_TIME >= :lookback
  GROUP BY USAGE_DATE, WAREHOUSE_NAME;

  DELETE FROM COST_DASHBOARD.PUBLIC.WAREHOUSE_DAILY
  WHERE USAGE_DATE < :cutoff;

  -- User daily
  DELETE FROM COST_DASHBOARD.PUBLIC.USER_DAILY
  WHERE USAGE_DATE >= :lookback;

  INSERT INTO COST_DASHBOARD.PUBLIC.USER_DAILY
  SELECT START_TIME::DATE AS USAGE_DATE, USER_NAME, SUM(CREDITS_USED_CLOUD_SERVICES) AS CREDITS
  FROM SNOWFLAKE.ACCOUNT_USAGE.QUERY_HISTORY
  WHERE START_TIME >= :lookback AND USER_NAME IS NOT NULL
  GROUP BY USAGE_DATE, USER_NAME;

  DELETE FROM COST_DASHBOARD.PUBLIC.USER_DAILY
  WHERE USAGE_DATE < :cutoff;

  -- Database storage daily
  DELETE FROM COST_DASHBOARD.PUBLIC.DATABASE_STORAGE_USAGE_HISTORY
  WHERE USAGE_DATE >= :lookback;

  INSERT INTO COST_DASHBOARD.PUBLIC.DATABASE_STORAGE_USAGE_HISTORY
  SELECT USAGE_DATE, DATABASE_NAME, AVERAGE_DATABASE_BYTES
  FROM SNOWFLAKE.ACCOUNT_USAGE.DATABASE_STORAGE_USAGE_HISTORY
  WHERE USAGE_DATE >= :lookback AND AVERAGE_DATABASE_BYTES > 0;

  DELETE FROM COST_DASHBOARD.PUBLIC.DATABASE_STORAGE_USAGE_HISTORY
  WHERE USAGE_DATE < :cutoff;

  -- CoCo usage
  DELETE FROM COST_DASHBOARD.PUBLIC.COCO_USAGE
  WHERE USAGE_DATE >= :lookback;

  INSERT INTO COST_DASHBOARD.PUBLIC.COCO_USAGE
  SELECT USER_NAME, USAGE_TIME::DATE AS USAGE_DATE, TOKEN_CREDITS, TOKENS,
         TOKENS_GRANULAR::VARCHAR, CREDITS_GRANULAR::VARCHAR,
         INTERFACE, METADATA::VARCHAR, THREAD_ID
  FROM SNOWFLAKE.ACCOUNT_USAGE.SNOWFLAKE_COCO_USAGE_HISTORY
  WHERE USAGE_TIME >= :lookback;

  DELETE FROM COST_DASHBOARD.PUBLIC.COCO_USAGE
  WHERE USAGE_DATE < :cutoff;

  -- ── Recommendation tables: full rebuild ──────────────────
  -- These need aggregate scores over the entire 90-day window,
  -- so incremental doesn't apply — rebuild is cheap (small output).

  CREATE OR REPLACE TABLE COST_DASHBOARD.PUBLIC.WAREHOUSE_SIZING AS
  SELECT WAREHOUSE_NAME, WAREHOUSE_SIZE, COUNT(*) AS TOTAL_QUERIES,
         ROUND(100.0 * SUM(CASE WHEN TOTAL_ELAPSED_TIME < 1000 THEN 1 ELSE 0 END) / COUNT(*), 1) AS OVERSIZED_PCT,
         ROUND(100.0 * SUM(CASE WHEN BYTES_SPILLED_TO_LOCAL_STORAGE + BYTES_SPILLED_TO_REMOTE_STORAGE > 0 THEN 1 ELSE 0 END) / COUNT(*), 1) AS SPILL_PCT,
         SUM(CASE WHEN TOTAL_ELAPSED_TIME > 60000 THEN 1 ELSE 0 END) AS HEAVY_QUERIES
  FROM SNOWFLAKE.ACCOUNT_USAGE.QUERY_HISTORY
  WHERE START_TIME >= :cutoff AND WAREHOUSE_NAME IS NOT NULL AND EXECUTION_STATUS = 'SUCCESS'
  GROUP BY WAREHOUSE_NAME, WAREHOUSE_SIZE
  HAVING COUNT(*) >= 100;

  CREATE OR REPLACE TABLE COST_DASHBOARD.PUBLIC.ADAPTIVE_SCORING AS
  WITH qh AS (
    SELECT WAREHOUSE_NAME, WAREHOUSE_SIZE, COUNT(*) AS TOTAL_QUERIES,
           STDDEV(TOTAL_ELAPSED_TIME) / NULLIF(AVG(TOTAL_ELAPSED_TIME), 0) AS VARIABILITY,
           ROUND(100.0 * SUM(CASE WHEN BYTES_SPILLED_TO_LOCAL_STORAGE + BYTES_SPILLED_TO_REMOTE_STORAGE > 0 THEN 1 ELSE 0 END) / COUNT(*), 1) AS SPILL_PCT,
           ROUND(100.0 * SUM(CASE WHEN TOTAL_ELAPSED_TIME < 1000 THEN 1 ELSE 0 END) / COUNT(*), 1) AS OVERSIZED_PCT,
           ROUND(100.0 * SUM(CASE WHEN TOTAL_ELAPSED_TIME > 60000 THEN 1 ELSE 0 END) / COUNT(*), 1) AS HEAVY_PCT,
           SUM(CASE WHEN QUEUED_PROVISIONING_TIME + QUEUED_OVERLOAD_TIME > 0 THEN 1 ELSE 0 END) AS QUEUED
    FROM SNOWFLAKE.ACCOUNT_USAGE.QUERY_HISTORY
    WHERE START_TIME >= :cutoff AND WAREHOUSE_NAME IS NOT NULL AND EXECUTION_STATUS = 'SUCCESS'
    GROUP BY WAREHOUSE_NAME, WAREHOUSE_SIZE HAVING COUNT(*) >= 100
  ),
  wm AS (
    SELECT WAREHOUSE_NAME, SUM(CREDITS_USED) AS CREDITS
    FROM SNOWFLAKE.ACCOUNT_USAGE.WAREHOUSE_METERING_HISTORY
    WHERE START_TIME >= :cutoff GROUP BY WAREHOUSE_NAME
  )
  SELECT qh.WAREHOUSE_NAME, qh.WAREHOUSE_SIZE, qh.TOTAL_QUERIES,
         ROUND(wm.CREDITS, 2) AS CREDITS, ROUND(qh.VARIABILITY, 2) AS VARIABILITY,
         qh.SPILL_PCT, qh.OVERSIZED_PCT, qh.HEAVY_PCT, qh.QUEUED,
         ROUND(LEAST(qh.VARIABILITY/3.0*40,40) + LEAST(qh.SPILL_PCT/25.0*30,30)
               + LEAST(qh.HEAVY_PCT/10.0*20,20) + LEAST(COALESCE(wm.CREDITS,0)/500.0*10,10), 1) AS SCORE
  FROM qh LEFT JOIN wm ON qh.WAREHOUSE_NAME = wm.WAREHOUSE_NAME
  WHERE LEAST(qh.VARIABILITY/3.0*40,40) + LEAST(qh.SPILL_PCT/25.0*30,30)
        + LEAST(qh.HEAVY_PCT/10.0*20,20) + LEAST(COALESCE(wm.CREDITS,0)/500.0*10,10) >= 25;

  CREATE OR REPLACE TABLE COST_DASHBOARD.PUBLIC.GEN2_SCORING AS
  WITH qh AS (
    SELECT WAREHOUSE_NAME, COUNT(*) AS TOTAL_QUERIES,
           ROUND(100.0 * SUM(CASE WHEN QUERY_TYPE IN ('DELETE','UPDATE','MERGE','INSERT') THEN 1 ELSE 0 END) / COUNT(*), 1) AS DML_PCT,
           ROUND(APPROX_PERCENTILE(TOTAL_ELAPSED_TIME, 0.95) / 1000.0, 1) AS P95_SEC,
           ROUND(100.0 * SUM(CASE WHEN BYTES_SPILLED_TO_LOCAL_STORAGE + BYTES_SPILLED_TO_REMOTE_STORAGE > 0 THEN 1 ELSE 0 END) / COUNT(*), 1) AS SPILL_PCT,
           ROUND(100.0 * SUM(CASE WHEN TOTAL_ELAPSED_TIME > 300000 THEN 1 ELSE 0 END) / COUNT(*), 1) AS LONG_PCT,
           SUM(CASE WHEN QUEUED_PROVISIONING_TIME + QUEUED_OVERLOAD_TIME > 0 THEN 1 ELSE 0 END) AS QUEUED
    FROM SNOWFLAKE.ACCOUNT_USAGE.QUERY_HISTORY
    WHERE START_TIME >= :cutoff AND WAREHOUSE_NAME IS NOT NULL AND EXECUTION_STATUS = 'SUCCESS'
    GROUP BY WAREHOUSE_NAME HAVING COUNT(*) >= 100
  ),
  wm AS (
    SELECT WAREHOUSE_NAME, SUM(CREDITS_USED) AS CREDITS
    FROM SNOWFLAKE.ACCOUNT_USAGE.WAREHOUSE_METERING_HISTORY
    WHERE START_TIME >= :cutoff GROUP BY WAREHOUSE_NAME
  )
  SELECT qh.WAREHOUSE_NAME, qh.TOTAL_QUERIES, ROUND(wm.CREDITS, 2) AS CREDITS,
         qh.DML_PCT, qh.P95_SEC, qh.SPILL_PCT, qh.LONG_PCT, qh.QUEUED,
         ROUND(LEAST(qh.DML_PCT/20.0*30,30) + LEAST(qh.SPILL_PCT/25.0*20,20)
               + LEAST(qh.LONG_PCT/10.0*20,20) + LEAST(qh.QUEUED/1000.0*15,15)
               + LEAST(COALESCE(wm.CREDITS,0)/500.0*15,15), 1) AS SCORE
  FROM qh LEFT JOIN wm ON qh.WAREHOUSE_NAME = wm.WAREHOUSE_NAME
  WHERE LEAST(qh.DML_PCT/20.0*30,30) + LEAST(qh.SPILL_PCT/25.0*20,20)
        + LEAST(qh.LONG_PCT/10.0*20,20) + LEAST(qh.QUEUED/1000.0*15,15)
        + LEAST(COALESCE(wm.CREDITS,0)/500.0*15,15) >= 25;

  CREATE OR REPLACE TABLE COST_DASHBOARD.PUBLIC.CLOUD_SERVICES_EXCESS AS
  SELECT WAREHOUSE_NAME,
         ROUND(SUM(CREDITS_USED_COMPUTE), 2) AS COMPUTE_CREDITS,
         ROUND(SUM(CREDITS_USED_CLOUD_SERVICES), 2) AS CS_CREDITS,
         ROUND(100.0 * SUM(CREDITS_USED_CLOUD_SERVICES) / NULLIF(SUM(CREDITS_USED_COMPUTE), 0), 1) AS CS_PCT,
         COUNT(DISTINCT START_TIME::DATE) AS ACTIVE_DAYS
  FROM SNOWFLAKE.ACCOUNT_USAGE.WAREHOUSE_METERING_HISTORY
  WHERE START_TIME >= :cutoff
  GROUP BY WAREHOUSE_NAME
  HAVING CS_PCT > 10 AND SUM(CREDITS_USED_COMPUTE) > 1;

  CREATE OR REPLACE TABLE COST_DASHBOARD.PUBLIC.CLUSTERING_WASTE AS
  SELECT DATABASE_NAME, SCHEMA_NAME, TABLE_NAME,
         ROUND(SUM(CREDITS_USED), 4) AS CLUSTERING_CREDITS, COUNT(*) AS EVENTS
  FROM SNOWFLAKE.ACCOUNT_USAGE.AUTOMATIC_CLUSTERING_HISTORY
  WHERE START_TIME >= :cutoff
  GROUP BY DATABASE_NAME, SCHEMA_NAME, TABLE_NAME
  HAVING CLUSTERING_CREDITS < 0.01;

  RETURN 'Refresh complete — 5 tables incremental, 5 tables rebuilt at ' || CURRENT_TIMESTAMP()::VARCHAR;
END;

-- ============================================================
-- 3. Initial load (full 90-day backfill)
-- ============================================================
CALL COST_DASHBOARD.PUBLIC.BACKFILL();

-- ============================================================
-- 4. Daily task — runs REFRESH() (incremental) at 6 AM UTC
-- ============================================================
CREATE OR REPLACE TASK COST_DASHBOARD.PUBLIC.REFRESH_DAILY
  WAREHOUSE = COST_DASHBOARD_WH
  SCHEDULE = 'USING CRON 0 6 * * * UTC'
AS
  CALL COST_DASHBOARD.PUBLIC.REFRESH();

ALTER TASK COST_DASHBOARD.PUBLIC.REFRESH_DAILY RESUME;

