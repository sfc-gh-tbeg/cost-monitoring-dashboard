export const QUERIES = {
  // Tab 1: Cost Monitor — reading from pre-loaded snapshot tables
  serviceBreakdown: `
    SELECT SERVICE_TYPE,
           USAGE_DATE,
           CREDITS_USED
    FROM COST_DASHBOARD.PUBLIC.METERING_DAILY_HISTORY
    WHERE USAGE_DATE >= DATEADD(day, ?, CURRENT_DATE())
    ORDER BY USAGE_DATE, SERVICE_TYPE`,

  warehouseDaily: `
    SELECT USAGE_DATE,
           WAREHOUSE_NAME,
           CREDITS
    FROM COST_DASHBOARD.PUBLIC.WAREHOUSE_DAILY
    WHERE USAGE_DATE >= DATEADD(day, ?, CURRENT_DATE())
    ORDER BY USAGE_DATE, WAREHOUSE_NAME`,

  userDaily: `
    SELECT USAGE_DATE,
           USER_NAME,
           CREDITS
    FROM COST_DASHBOARD.PUBLIC.USER_DAILY
    WHERE USAGE_DATE >= DATEADD(day, ?, CURRENT_DATE())
    ORDER BY USAGE_DATE, USER_NAME`,

  storageDaily: `
    SELECT USAGE_DATE,
           DATABASE_NAME,
           AVERAGE_DATABASE_BYTES
    FROM COST_DASHBOARD.PUBLIC.DATABASE_STORAGE_USAGE_HISTORY
    WHERE USAGE_DATE >= DATEADD(day, ?, CURRENT_DATE())
    ORDER BY USAGE_DATE, DATABASE_NAME`,

  // Tab 2: AI Usage (CoCo) — from pre-loaded snapshot table
  cocoSummary: `
    SELECT COUNT(*) AS TOTAL_REQUESTS,
           SUM(TOKEN_CREDITS) AS TOTAL_TOKEN_CREDITS,
           SUM(TOKENS) AS TOTAL_TOKENS,
           COUNT(DISTINCT USER_NAME) AS PEAK_USERS,
           COUNT(DISTINCT THREAD_ID) AS TOTAL_SESSIONS
    FROM COST_DASHBOARD.PUBLIC.COCO_USAGE
    WHERE USAGE_DATE >= DATEADD(day, ?, CURRENT_DATE())`,

  cocoTokenBreakdown: `
    SELECT USER_NAME,
           USAGE_DATE,
           SUM(TOKEN_CREDITS) AS TOKEN_CREDITS,
           SUM(TOKENS) AS TOKENS,
           INTERFACE,
           COUNT(*) AS REQUEST_COUNT,
           COUNT(DISTINCT THREAD_ID) AS SESSION_COUNT
    FROM COST_DASHBOARD.PUBLIC.COCO_USAGE
    WHERE USAGE_DATE >= DATEADD(day, ?, CURRENT_DATE())
    GROUP BY USER_NAME, USAGE_DATE, INTERFACE
    ORDER BY USAGE_DATE DESC`,

  cocoModelBreakdown: `
    SELECT f.key AS MODEL,
           SUM(v.value::FLOAT) AS CREDITS
    FROM COST_DASHBOARD.PUBLIC.COCO_USAGE,
         LATERAL FLATTEN(input => PARSE_JSON(CREDITS_GRANULAR)) f,
         LATERAL FLATTEN(input => f.value) v
    WHERE USAGE_DATE >= DATEADD(day, ?, CURRENT_DATE())
    GROUP BY f.key
    ORDER BY CREDITS DESC`,
} as const
